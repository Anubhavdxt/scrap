#!/usr/bin/env python3
"""Generates Sources/ScrapCore/Themes.generated.swift from the portfolio's theme files.

Usage: scripts/gen_themes.py <portfolio-dir>

Themes with explicit highlight.js CSS use those colours. The rest derive them from the
theme's CSS variables, mirroring the fallback rules in the portfolio's index.css.
"""
import colorsys, pathlib, re, sys

root = pathlib.Path(sys.argv[1])
syntax = (root / "src/lib/syntax-themes.css").read_text()
index = (root / "src/index.css").read_text()
ts = (root / "src/lib/themes.ts").read_text()

# token -> highlight.js classes to try, in order
TOKENS = {
    "comment": ["comment", "quote"], "keyword": ["keyword", "selector-tag"],
    "title": ["title", "section", "function"], "type": ["type", "built_in", "class"],
    "builtin": ["built_in", "type"], "number": ["number", "literal"], "string": ["string"],
    "subst": ["subst", "params"], "attr": ["attr", "attribute", "property", "name", "tag"],
    "variable": ["variable"], "operator": ["operator"], "punctuation": ["punctuation"],
    "deletion": ["deletion"],
}
ORDER = ["base"] + list(TOKENS)
# when a theme defines none of a token's classes
FALLBACK = {"variable": "base", "punctuation": "base", "operator": "keyword", "deletion": "number",
            "subst": "base", "string": "base", "number": "base", "keyword": "base", "title": "base",
            "type": "title", "builtin": "type", "attr": "base", "comment": "base"}

families = {}
for m in re.finditer(
    r"id: '([^']+)', name: '([^']+)', dark: \{ bg: '(#\w+)', accent: '(#\w+)' \}, light: \{ bg: '(#\w+)', accent: '(#\w+)' \}", ts):
    fid, name, dbg, dac, lbg, lac = m.groups()
    families[fid] = (name, {"dark": (dbg, dac), "light": (lbg, lac)})

def hexint(h):
    return "0x" + h.lstrip("#").upper()

# ---- explicit highlight.js themes
explicit = {}  # theme id -> {class: (hex, italic)}
for m in re.finditer(r'((?:\[data-theme="[^"]+"\][^,{]*,?\s*)+)\{([^}]*)\}', syntax):
    sels, body = m.groups()
    color = re.search(r"(?<![-\w])color:\s*(#\w+)", body)
    if not color:
        continue
    for sel in sels.split(","):
        s = re.match(r'\s*\[data-theme="([^"]+)"\] \.prose-kaer (?:\.hljs-([\w]+)|(\.hljs))\s*$', sel)
        if s:
            tid, cls, base = s.groups()
            explicit.setdefault(tid, {})["base" if base else cls] = (color.group(1), "italic" in body)

# ---- derived from CSS variables
def css_vars(tid):
    m = re.search(r'\[data-theme="%s"\]\s*\{([^}]*)\}' % re.escape(tid), index)
    return dict(re.findall(r"--([\w-]+):\s*([^;]+);", m.group(1)))

def hsl(v):
    h, s, l = [float(x.strip("%")) for x in v.split()]
    r, g, b = colorsys.hls_to_rgb(h / 360, l / 100, s / 100)
    return (r * 255, g * 255, b * 255)

def mix(a, b, pa):
    return tuple(x * pa + y * (1 - pa) for x, y in zip(a, b))

def to_hex(c):
    return "#%02X%02X%02X" % tuple(round(min(255, max(0, x))) for x in c)

def resolve_explicit(tid):
    have = explicit[tid]
    out = {"base": have.get("base") or (to_hex(hsl(css_vars(tid)["foreground"])), False)}
    for tok, classes in TOKENS.items():
        hit = next((have[c] for c in classes if c in have), None)
        if hit:
            out[tok] = hit
    for tok in ORDER:
        out.setdefault(tok, out[FALLBACK[tok]] if tok in FALLBACK else out["base"])
    return {k: (v[0], v[1]) for k, v in out.items()}

def resolve_derived(tid):
    v = css_vars(tid)
    fg, prim, acc, des, mut = (hsl(v[k]) for k in ("foreground", "primary", "accent", "destructive", "muted-foreground"))
    title = mix(prim, fg, 0.55); typ = mix(acc, fg, 0.60); attr = mix(fg, prim, 0.85)
    cols = {"base": fg, "keyword": prim, "string": acc, "number": des, "deletion": des, "title": title,
            "type": typ, "builtin": typ, "attr": attr, "variable": attr, "subst": attr,
            "comment": mut, "punctuation": mut, "operator": mut}
    return {k: (to_hex(c), k == "comment") for k, c in cols.items()}

out = ["// GENERATED by scripts/gen_themes.py. Do not edit by hand.", "",
       "extension Themes {", "    static let generated: [Theme] = ["]
count = 0
for fid, (name, modes) in families.items():
    for mode in ("dark", "light"):
        tid = f"{fid}-{mode}"
        tokens = resolve_explicit(tid) if tid in explicit else resolve_derived(tid)
        assert set(tokens) == set(ORDER), (tid, set(ORDER) ^ set(tokens))
        bg, ac = modes[mode]
        cols = ", ".join(f".{t}: {hexint(tokens[t][0])}" for t in ORDER)
        ital = ", ".join(f".{t}" for t in ORDER if tokens[t][1])
        out.append(f'        Theme(id: "{tid}", family: "{fid}", name: "{name}", isDark: {str(mode == "dark").lower()},')
        out.append(f"              background: {hexint(bg)}, accent: {hexint(ac)},")
        out.append(f"              colors: [{cols}],")
        out.append(f"              italic: [{ital}]),")
        count += 1
out += ["    ]", "}", ""]
pathlib.Path("Sources/ScrapCore/Themes.generated.swift").write_text("\n".join(out))
print(len(families), "families,", count, "themes,", len(explicit), "explicit")
